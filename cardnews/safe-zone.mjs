/** 1080 기준 값을 다른 폭으로 환산한다. (720 → ×2/3) */
export const 환산 = (값, 폭) => Math.round((값 * 폭) / 측정.기준.w);

/**
 * **글자·자막**이 지켜야 하는 경계. 구도값과 달리 이건 타협하지 않는다 —
 * 글자가 UI 아래 깔리면 그 회차는 읽을 수 없다.
 * @param {number} w 프레임 폭 (예: 720)
 * @param {number} h 프레임 높이 (예: 1280)
 */
export function 글자안전(w, h) {
  return {
    /** y 가 이보다 작으면 상단 nav 와 겹친다 */
    상단: 환산(측정.상단nav, w),
    /** 블록 바닥이 이보다 크면 캡션·프로필과 겹친다 */
    하단임계: h - 환산(측정.하단UI, w),
    /** 블록 오른쪽 끝이 이보다 크면 버튼 열과 겹친다 */
    우측임계: w - 환산(측정.우측버튼열, w),
  };
}

/**
 * 글자 블록 하나를 검사한다. 경고 문자열 배열을 돌려준다(비어 있으면 안전).
 * ⚠️ `우측끝` 은 부르는 쪽이 계산해서 넘긴다 — 폰트 폭 근사는 도구마다 다르다.
 */
export function 검사글자({ y, 바닥, 우측끝, w, h, 세로반영 = false }) {
  const s = 글자안전(w, h);
  const warns = [];
  // 세로반영: 버튼 열은 프레임 y (시작y − 여유) 아래에만 있다(2026-09-29 실측). 블록 바닥이 그 위면 오른쪽 검사를 건너뛴다.
  //   ⛔ 기본은 꺼짐 — 켜는 쪽(모션 layout: center)만 쓴다. 가로 끝은 프레임 폭을 넘으면 안 되는 건 그대로다.
  if (세로반영 && 바닥 <= 환산(측정.우측버튼열_시작y - 측정.우측버튼열_여유, w)) {
    if (y < s.상단) warns.push(`상단 ${y}px 가 상단 nav 구역(${s.상단}px) 안이다 ⚠️ 이 값은 미측정이다`);
    if (우측끝 > w - 환산(76, w)) warns.push(`오른쪽 끝 ${Math.round(우측끝)}px 가 프레임 오른쪽 여백(${w - 환산(76, w)}px) 밖이다`);
    return warns;
  }
  if (y < s.상단) warns.push(`상단 ${y}px 가 상단 nav 구역(${s.상단}px) 안이다 ⚠️ 이 값은 미측정이다`);
  if (바닥 > s.하단임계) {
    warns.push(`바닥 ${Math.round(바닥)}px 가 캡션·프로필 구역(임계 ${s.하단임계}px) 안이다`
      + ` — 실측 ${측정.하단UI}px@1080, ${측정.날짜}`);
  }
  if (우측끝 > s.우측임계) {
    warns.push(`오른쪽 끝 ${Math.round(우측끝)}px 가 버튼 열(임계 ${s.우측임계}px) 안이다`
      + ` — 실측 ${측정.우측버튼열}px@1080, ${측정.날짜}`);
  }
  return warns;
}
